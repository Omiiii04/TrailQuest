package com.example.trailquest

import com.example.trailquest.ui.setup.ExpeditionActivity
import com.example.trailquest.ui.setup.ExpeditionConfig
import com.example.trailquest.ui.setup.ExpeditionDifficulty
import com.example.trailquest.ui.setup.ExpeditionDraftState
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class MissionGenerationFlowTest {

    private class FakeLlmProvider : LlmProvider {
        var transactionCount = 0
        var isGenerating = false
        var duplicateAttemptCount = 0

        override suspend fun loadModel(path: String) {}
        override suspend fun setSystemPrompt(prompt: String) {}
        override fun generate(prompt: String) = kotlinx.coroutines.flow.emptyFlow<String>()
        override suspend fun benchmark(): String = "bench"
        override suspend fun resetContext() {}
        override suspend fun setThreads(threads: Int) {}
        override fun getRecommendedThreads(): Int = 4
        override fun cleanup() {}

        override suspend fun runTransaction(
            prompt: String,
            systemPrompt: String?,
            threads: Int?,
            onToken: ((token: String, accumulated: String) -> Boolean)?
        ): String {
            if (isGenerating) {
                duplicateAttemptCount++
                throw IllegalStateException("Duplicate transaction attempted while busy")
            }
            isGenerating = true
            try {
                transactionCount++
                return "{\"title\": \"Walk\", \"durationMinutes\": 30, \"missions\": [\"Walk\"]}"
            } finally {
                isGenerating = false
            }
        }
    }

    @Test
    fun setupDraftState_survivesBackAndForwardNavigation() {
        val draft = ExpeditionDraftState()

        // Configure initial Hike 30m Moderate
        draft.selectedActivity = ExpeditionActivity.HIKE
        draft.selectedDurationMinutes = 30
        draft.selectedDifficulty = ExpeditionDifficulty.MODERATE

        val config1 = draft.buildConfig()
        assertEquals(ExpeditionActivity.HIKE, config1.activity)
        assertEquals(30, config1.durationMinutes)
        assertEquals(ExpeditionDifficulty.MODERATE, config1.difficulty)

        // User navigates back to setup and edits difficulty
        draft.selectedDifficulty = ExpeditionDifficulty.CHALLENGING
        val config2 = draft.buildConfig()

        assertEquals(ExpeditionActivity.HIKE, config2.activity)
        assertEquals(30, config2.durationMinutes)
        assertEquals(ExpeditionDifficulty.CHALLENGING, config2.difficulty)
    }

    @Test
    fun generationGuard_preventsDuplicateConcurrentTaps() {
        var isGenerating = false
        var startedJobs = 0

        fun triggerTap() {
            if (isGenerating) return
            isGenerating = true
            startedJobs++
        }

        // First tap initiates generation
        triggerTap()
        assertEquals(1, startedJobs)
        assertTrue(isGenerating)

        // Rapid subsequent taps while isGenerating == true are discarded
        triggerTap()
        triggerTap()
        triggerTap()
        assertEquals("Subsequent taps must be suppressed while isGenerating == true", 1, startedJobs)

        // Once generation completes, isGenerating is reset
        isGenerating = false
        triggerTap()
        assertEquals(2, startedJobs)
    }

    @Test
    fun oneShotAutoGenerateFlag_isConsumedOnce() {
        var hasAutoGenerated = false
        var executionCount = 0

        fun onEvent(autoGenerate: Boolean) {
            if (autoGenerate && !hasAutoGenerated) {
                hasAutoGenerated = true
                executionCount++
            }
        }

        // First event triggers execution
        onEvent(true)
        assertEquals(1, executionCount)
        assertTrue(hasAutoGenerated)

        // Recompositions with autoGenerate = true do not re-trigger
        onEvent(true)
        onEvent(true)
        assertEquals(1, executionCount)
    }
}
